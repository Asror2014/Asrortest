function selectTextbook(bookId) {
  AppState.currentTextbook = bookId;

  var grid = document.getElementById('textbook-grid');
  var chaptersSection = document.getElementById('textbook-chapters');
  var titleEl = document.getElementById('textbook-title');
  var listEl = document.getElementById('chapters-list');

  if (grid) grid.style.display = 'none';
  if (chaptersSection) chaptersSection.style.display = 'block';

  var bookData = getTextbookData(bookId);

  if (titleEl) {
    titleEl.innerHTML = '<i class="' + bookData.icon + '" style="color:' + bookData.color + '"></i> ' + bookData.title;
  }

  if (listEl) {
    listEl.innerHTML = '';
    bookData.chapters.forEach(function (ch, idx) {
      var item = document.createElement('div');
      item.className = 'chapter-item' + (idx === 0 ? ' active' : '');
      item.innerHTML = '<div style="font-weight:700; color:#fff; font-size:1.05rem; margin-bottom:4px;">' + (idx + 1) + '-bob: ' + ch.title + '</div>' +
                       '<div style="font-size:0.85rem; color:#94a3b8;">' + ch.subtitle + '</div>';
      item.onclick = function () {
        var all = listEl.querySelectorAll('.chapter-item');
        all.forEach(function (el) { el.classList.remove('active'); });
        item.classList.add('active');
        renderChapterContent(ch, bookData);
      };
      listEl.appendChild(item);
    });
  }

  if (bookData.chapters && bookData.chapters.length > 0) {
    renderChapterContent(bookData.chapters[0], bookData);
  }

  window.scrollTo({ top: 120, behavior: 'smooth' });
}

