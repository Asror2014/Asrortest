function saveModalQuestion() {
  var grade = document.getElementById('modal-grade-select').value;
  var subject = document.getElementById('modal-subject-select').value;
  var diff = document.getElementById('modal-diff-select').value;
  var qText = document.getElementById('modal-q-text').value.trim();
  var optA = document.getElementById('modal-opt-a').value.trim();
  var optB = document.getElementById('modal-opt-b').value.trim();
  var optC = document.getElementById('modal-opt-c').value.trim();
  var optD = document.getElementById('modal-opt-d').value.trim();
  var checkedRadio = document.querySelector('input[name="modal-correct"]:checked');
  var correctOpt = checkedRadio ? parseInt(checkedRadio.value, 10) : 0;
  var expl = document.getElementById('modal-q-expl').value.trim();

  if (!qText || !optA || !optB || !optC || !optD) {
    showNotification("Iltimos, savol matni va barcha 4 ta javob variantini to'ldiring!", "error");
    return;
  }

  var key = grade + '_' + subject;
  if (!window.TEST_DATA) window.TEST_DATA = {};
  if (!window.TEST_DATA[key]) window.TEST_DATA[key] = [];

  var newQ = {
    q: qText,
    options: [optA, optB, optC, optD],
    answer: correctOpt,
    difficulty: diff,
    explanation: expl || ("To'g'ri javob: " + ['A', 'B', 'C', 'D'][correctOpt] + " varianti")
  };

  window.TEST_DATA[key].unshift(newQ);

  try {
    var stored = JSON.parse(localStorage.getItem('30_maktab_custom_tests') || '[]');
    stored.unshift({ key: key, q: newQ });
    localStorage.setItem('30_maktab_custom_tests', JSON.stringify(stored));
  } catch (err) {}

  showNotification("âœ… Yangi test savoli muvaffaqiyatli saqlandi va " + grade + "-sinf " + subject + " testlariga qo'shildi!", "success");

  document.getElementById('modal-q-text').value = '';
  document.getElementById('modal-opt-a').value = '';
  document.getElementById('modal-opt-b').value = '';
  document.getElementById('modal-opt-c').value = '';
  document.getElementById('modal-opt-d').value = '';
  document.getElementById('modal-q-expl').value = '';
}

function toggleMobileMenu() {
  var navLinks = document.getElementById('nav-links');
  var btn = document.getElementById('mobile-menu-btn');
  if (!navLinks) return;
  var isOpen = navLinks.classList.toggle('mobile-active');
  if (btn) {
    btn.classList.toggle('active', isOpen);
    var icon = btn.querySelector('i');
    if (icon) {
      icon.className = isOpen ? 'fas fa-times' : 'fas fa-bars';
    }
    var label = btn.querySelector('.mobile-menu-label');
    if (label) {
      label.textContent = isOpen ? 'Yopish' : 'Menyu';
    }
  }
}

// Tashqariga bosilganda mobil menyuni yopish
document.addEventListener('click', function (e) {
  var navLinks = document.getElementById('nav-links');
  var btn = document.getElementById('mobile-menu-btn');
  if (!navLinks || !navLinks.classList.contains('mobile-active')) return;
  if (!navLinks.contains(e.target) && !btn.contains(e.target)) {
    navLinks.classList.remove('mobile-active');
    if (btn) {
      btn.classList.remove('active');
      var icon = btn.querySelector('i');
      if (icon) icon.className = 'fas fa-bars';
      var label = btn.querySelector('.mobile-menu-label');
      if (label) label.textContent = 'Menyu';
    }
  }
});

