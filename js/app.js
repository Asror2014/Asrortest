function renderTeacherStudents(gradeFilter) {
  var tbody = document.getElementById('teacher-students-tbody');
  if (!tbody) return;

  var list = [];

  // Agar AccountsManager bazasi (686 ta o'quvchi) mavjud bo'lsa, undan to'liq foydalanamiz
  if (window.AccountsManager && Array.isArray(window.AccountsManager.accounts) && window.AccountsManager.accounts.length > 0) {
    var accs = window.AccountsManager.accounts.slice();
    if (gradeFilter && gradeFilter !== 'all') {
      if (gradeFilter.indexOf('-') !== -1) {
        var p = gradeFilter.split('-');
        var g = parseInt(p[0], 10);
        var l = p[1];
        accs = accs.filter(function(a) { return a.grade === g && (a.classLetter || 'A') === l; });
      } else {
        var gOnly = parseInt(gradeFilter, 10);
        accs = accs.filter(function(a) { return a.grade === gOnly; });
      }
    }
    accs.sort(function(a, b) { return (b.score || 0) - (a.score || 0); });

    accs.forEach(function(a, idx) {
      var eff = a.effortLevel || (idx < 5 ? 'high' : (idx >= accs.length - 6 ? 'low' : 'medium'));
      var stLabel = eff === 'high' ? "🔥 Katta harakat" : (eff === 'low' ? "⚠️ Kam harakat" : "⚡ O'rtacha");
      var badgeColor = eff === 'high' ? "#10b981" : (eff === 'low' ? "#ef4444" : "#3b82f6");
      list.push({
        id: a.id,
        name: (a.avatar || '🎓') + ' ' + a.firstName + ' ' + (a.lastName || ''),
        grade: a.grade + '-' + (a.classLetter || 'A'),
        subject: "Barcha fanlar",
        correct: (a.testsCompleted || 0) * 18,
        total: (a.testsCompleted || 0) * 20,
        score: (a.score || 0) + ' ball',
        gradeLetter: a.accuracy ? a.accuracy + '%' : '0%',
        date: "2026-2027",
        status: stLabel,
        color: badgeColor
      });
    });
  } else {
    list = teacherMockStudents.slice();
    if (gradeFilter && gradeFilter !== 'all') {
      list = list.filter(function (s) { return s.grade === parseInt(gradeFilter, 10); });
    }
  }

  var html = '';
  list.forEach(function (s, index) {
    var badgeColor = s.color || (s.status === "A'lo" ? "#10b981" : (s.status === "Yaxshi" ? "#3b82f6" : "#f59e0b"));
    html += '<tr>' +
      '<td><strong>#' + (index + 1) + '</strong></td>' +
      '<td>' + s.name + '</td>' +
      '<td>' + (typeof s.grade === 'string' && s.grade.indexOf('sinf') !== -1 ? s.grade : s.grade + '-sinf') + '</td>' +
      '<td>' + s.subject + '</td>' +
      '<td><strong>' + s.correct + ' / ' + s.total + '</strong></td>' +
      '<td><span style="font-weight:700; color:#fbbf24;">' + s.score + ' (' + s.gradeLetter + ')</span></td>' +
      '<td>' + s.date + '</td>' +
      '<td><span class="teacher-status-badge" style="background:' + badgeColor + '22; color:' + badgeColor + '; border:1px solid ' + badgeColor + '44;">' + s.status + '</span></td>' +
      '</tr>';
  });

  tbody.innerHTML = html;
}

