function navigateTo(pageId) {
  if (!pageId) return;

  var cleanId = pageId.replace(/^page-/, '');
  var fullId = 'page-' + cleanId;

  // Header ko'rinishi: Test jarayonida yashiriladi, qolgan sahifalarda ko'rinadi
  var header = document.getElementById('main-header');
  if (header) {
    if (cleanId === 'test') {
      header.style.setProperty('display', 'none', 'important');
      document.body.classList.add('in-test');
    } else {
      header.style.setProperty('display', 'flex', 'important');
      document.body.classList.remove('in-test');
    }
  }

  // Mobil menyu ochiq bo'lsa, yopish
  var navLinksMenu = document.getElementById('nav-links');
  if (navLinksMenu && navLinksMenu.classList.contains('mobile-active')) {
    navLinksMenu.classList.remove('mobile-active');
  }
  var navBtn = document.getElementById('mobile-menu-btn');
  if (navBtn) {
    navBtn.classList.remove('active');
    var navIcon = navBtn.querySelector('i');
    if (navIcon) navIcon.className = 'fas fa-bars';
    var navLabel = navBtn.querySelector('.mobile-menu-label');
    if (navLabel) navLabel.textContent = 'Menyu';
  }

  // Navigatsiya linklarini aktiv qilish
  var navLinks = document.querySelectorAll('.nav-links a');
  navLinks.forEach(function (a) {
    var navAttr = a.getAttribute('data-nav');
    if ((cleanId === 'landing' || cleanId === 'dashboard') && navAttr === 'dashboard') {
      a.classList.add('active');
    } else if (cleanId.indexOf('test') !== -1 && navAttr === 'tests') {
      a.classList.add('active');
    } else if (cleanId.indexOf('lab') !== -1 && navAttr === 'lab') {
      a.classList.add('active');
    } else if (cleanId === 'textbook' && navAttr === 'books') {
      a.classList.add('active');
    } else if (cleanId === 'teacher' && navAttr === 'teacher') {
      a.classList.add('active');
    } else if (cleanId === 'olympiad' && navAttr === 'olympiad') {
      a.classList.add('active');
    } else {
      a.classList.remove('active');
    }
  });

  if (cleanId.indexOf('lab') !== -1 && window.AchievementsManager) {
    window.AchievementsManager.checkOnLabVisit(cleanId);
  }

  // Barcha sahifalarni yashirish
  var sections = document.querySelectorAll('.page-section');
  sections.forEach(function (sec) {
    sec.style.setProperty('display', 'none', 'important');
    sec.classList.remove('active');
  });

  // Maqsadli bo'limni ko'rsatish
  var target = document.getElementById(fullId);
  if (target) {
    target.style.setProperty('display', 'block', 'important');
    target.classList.add('active');
  }

  AppState.currentPage = cleanId;

  // Footer boshqaruvi: 3D laboratoriyalar va faol test paytida footerni yashirish
  var mainFooter = document.getElementById('main-footer');
  if (mainFooter) {
    var hideFooterPages = ['chemistry-lab', 'physics-lab', 'astronomy-lab', 'biology-lab', 'geometry-lab', 'technology-lab', 'active-test'];
    if (hideFooterPages.indexOf(cleanId) !== -1) {
      mainFooter.style.display = 'none';
    } else {
      mainFooter.style.display = 'block';
    }
  }

  // 3D Laboratoriya ochilganda Three.js sahnasini ishga tushirish
  if (cleanId === 'chemistry-lab') {
    setTimeout(function () {
      if (typeof window.initChemistryLab === 'function') window.initChemistryLab();
      var ov = document.getElementById('chemistry-canvas-overlay');
      if (ov) ov.style.display = 'none';
    }, 150);
  }
  if (cleanId === 'physics-lab') {
    setTimeout(function () {
      if (typeof window.initPhysicsLab === 'function') window.initPhysicsLab();
      var ov = document.getElementById('physics-canvas-overlay');
      if (ov) ov.style.display = 'none';
    }, 150);
  }
  if (cleanId === 'astronomy-lab') {
    setTimeout(function () {
      if (typeof window.initAstronomyLab === 'function') window.initAstronomyLab();
      var ov = document.getElementById('astronomy-canvas-overlay');
      if (ov) ov.style.display = 'none';
    }, 150);
  }
  if (cleanId === 'biology-lab') {
    setTimeout(function () {
      if (typeof window.initBiologyLab === 'function') window.initBiologyLab();
      var ov = document.getElementById('biology-canvas-overlay');
      if (ov) ov.style.display = 'none';
    }, 150);
  }
  if (cleanId === 'geometry-lab') {
    setTimeout(function () {
      if (typeof window.initGeometryLab === 'function') window.initGeometryLab();
      var ov = document.getElementById('geometry-canvas-overlay');
      if (ov) ov.style.display = 'none';
    }, 150);
  }
  if (cleanId === 'technology-lab') {
    setTimeout(function () {
      if (typeof window.initTechnologyLab === 'function') window.initTechnologyLab();
      var ov = document.getElementById('technology-canvas-overlay');
      if (ov) ov.style.display = 'none';
      var params = new URLSearchParams(window.location.search);
      var exp = params.get('tech_exp');
      if (exp && typeof window.selectTechnologyExperiment === 'function') {
        window.selectTechnologyExperiment(exp);
      }
      if (params.get('finish_print') === '1' && typeof window.instantFinish3DPrinter === 'function') {
        window.instantFinish3DPrinter();
      }
    }, 150);
  }

  // O'qituvchilar paneli ochilganda
  if (cleanId === 'teacher') {
    initTeacherPortal();
  }

  // Sahifaning yuqorisiga o'tish
  window.scrollTo({ top: 0, behavior: 'smooth' });
}

