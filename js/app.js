function scrollToTestCenter() {
  if (AppState.currentPage !== 'landing') {
    var initPage = (window.location.hash && window.location.hash.length > 1) ? window.location.hash.substring(1) : 'page-landing';
  navigateTo(initPage);
  window.addEventListener('hashchange', function() {
    if (window.location.hash && window.location.hash.length > 1) {
      navigateTo(window.location.hash.substring(1));
    }
  });
  }
  setTimeout(function () {
    var el = document.getElementById('home-test-center');
    if (el) {
      var headerHeight = 75;
      var topPos = el.getBoundingClientRect().top + window.pageYOffset - headerHeight;
      window.scrollTo({ top: topPos, behavior: 'smooth' });
    }
  }, 100);
}

function selectGrade(grade) {
  AppState.selectedGrade = parseInt(grade, 10);

  // Barcha sinf kartalarini yangilash (Home va Dashboard)
  var allGradeCards = document.querySelectorAll('.home-grade-card, .grade-card');
  allGradeCards.forEach(function (c) {
    if (parseInt(c.getAttribute('data-grade'), 10) === AppState.selectedGrade) {
      c.classList.add('selected');
    } else {
      c.classList.remove('selected');
    }
  });

  // Sarlavhalarni yangilash
  var titleText = document.getElementById('home-grade-title-text');
  if (titleText) titleText.textContent = AppState.selectedGrade + '-sinf';
  var selGradeText = document.getElementById('selected-grade-text');
  if (selGradeText) selGradeText.textContent = AppState.selectedGrade + '-sinf';

  // Fanlar ro'yxatini render qilish
  var subjects = (window.SUBJECTS_BY_GRADE && window.SUBJECTS_BY_GRADE[AppState.selectedGrade]) || [];
  var grids = [document.getElementById('home-subjects-grid'), document.getElementById('subject-grid')];

  grids.forEach(function (grid) {
    if (!grid) return;
    var html = '';
    subjects.forEach(function (sub, idx) {
      var iconInfo = (window.SUBJECT_ICONS && window.SUBJECT_ICONS[sub.id]) || { faIcon: 'fa-book', color: '#6366F1', name: sub.name };
      var count = 30;
      var key = AppState.selectedGrade + '_' + sub.id;
      if (window.TEST_DATA && window.TEST_DATA[key]) {
        count = window.TEST_DATA[key].length;
      }
      var isFirst = (idx === 0);

      html += '<div class="home-subject-card subject-card' + (isFirst ? ' selected' : '') + '" data-subject="' + sub.id + '" onclick="selectSubject(\'' + sub.id + '\')" style="--subj-color: ' + (sub.color || iconInfo.color) + ';">' +
        '<div class="home-subject-card-icon subject-card-icon" style="background: ' + (sub.color || iconInfo.color) + '22; color: ' + (sub.color || iconInfo.color) + ';">' +
        '<i class="fas ' + (iconInfo.faIcon || 'fa-graduation-cap') + '"></i>' +
        '</div>' +
        '<div class="home-subject-card-info">' +
        '<h4 class="home-subject-card-title">' + sub.name + '</h4>' +
        '<span class="home-subject-card-badge">' + count + '+ ta savol</span>' +
        '</div>' +
        '</div>';
    });
    grid.innerHTML = html;
  });

  // Birinchi fanni avtomatik belgilash
  if (subjects.length > 0) {
    AppState.selectedSubject = subjects[0].id;
    updateTestStartButton();
  }

  showNotification(AppState.selectedGrade + "-sinf fanlari yuklandi", "info");
}

