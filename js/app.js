function setQuestionCount(count) {
  var num = parseInt(count, 10);
  if (isNaN(num) || num < 5) num = 5;
  if (num > 100) num = 100;

  AppState.testConfig.questionCount = num;

  var inputs = document.querySelectorAll('#question-count');
  inputs.forEach(function (inp) { inp.value = num; });

  var btns = document.querySelectorAll('.count-btn, .quick-btn');
  btns.forEach(function (btn) {
    var bCount = parseInt(btn.getAttribute('data-count'), 10) || parseInt(btn.textContent, 10);
    if (bCount === num) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  updateTestStartButton();
  showNotification(num + " ta savol belgilandi", "info");
}

